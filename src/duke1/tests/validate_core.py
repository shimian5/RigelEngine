"""Compare independent C++ state transitions against original DOS stage1 probes.
Golden records are generated by original instructions, never by the C++ under test.
No game binary is needed by the C++ library or launcher adapter.
"""
import json,subprocess,sys
from pathlib import Path
B=Path(sys.argv[1]);R=Path(sys.argv[2]);checks=0;rows_compared=0

def run(commands):
 p=subprocess.run([str(B)],input='\n'.join(commands)+'\n',text=True,capture_output=True,timeout=5)
 assert p.returncode==0,(commands,p.stderr)
 return [json.loads(v) for v in p.stdout.splitlines()]
def equal(actual,expected,label):
 global checks,rows_compared
 checks+=1;rows_compared+=len(actual)
 assert len(actual)==len(expected),(label,len(actual),len(expected))
 for n,(a,e) in enumerate(zip(actual,expected)):
  assert {k:a[k] for k in e}==e,(label,n,a,e)
def load(name):return json.loads((R/'out/stage1'/name).read_text())
movement=load('player-core-probes.json')
for name,expected in movement.items():
 c=['reset','queries 1 1 1 0'];expected=expected if isinstance(expected,list) else [expected]
 if name.startswith('jump_boost_'):
  c+=['set boost '+name[-1],'input 0 0 0 0 1 0','move','queries 1 1 1 1']+['move']*(len(expected)-1)
 elif name in ('walk_left','walk_right','turn_left_then_walk'):
  left=name!='walk_right';c+=['set facing '+('4' if name=='turn_left_then_walk' or not left else '0'),f'input {int(left)} {int(not left)} 0 0 0 0']+['move']*len(expected)
 elif name.startswith('fall_from_'):
  c+=['queries 1 1 1 1','set ground 0','set fall 1','set y '+name.split('_')[-1],'move']
 elif name=='both_horizontal_keys':c+=['input 1 1 0 0 0 0','move']
 elif name=='blocked_left':c+=['set facing 0','queries 0 1 1 0','input 1 0 0 0 0 0','move']
 elif name=='blocked_jump':c+=['queries 1 1 0 1','set ground 0','set fall 0','move']
 else:raise AssertionError('new original fixture needs adapter: '+name)
 equal(run(c),expected,name)

camera=load('camera-backdrop-probes.json')['vertical_camera']
for n,r in enumerate(camera):
 b=r['before'];c=['reset',f"set y {b['y']}",f"set cy {b['camera_y_words']}",f"set enabled {b['enabled']}",f"set lock {b['lock']}",'camera'];a=run(c)[0]
 equal([{'y':a['y_px'],'camera_y_words':a['camera_y_words'],'enabled':a['enabled']}],[r['after']],f'vertical camera{n}')

services=load('collision-services-probes.json')
for n,r in enumerate(services['collision']):
 sensor={'0x1ba9':'left','0x1c30':'right','0x1cb4':'head','0x1da0':'floor'}[r['helper']]
 a=run(['reset',f"fill {r['tile_value']}",f"set claw {r['cling_ability']}",f'collision {sensor}'])[0]
 equal([{'returns_clear':a['returns_clear'],'cling_state':a['cling_state'],'events':[{'sound_request':x} for x in a['sound_requests']]}],[{k:r[k] for k in ('returns_clear','cling_state','events')}],f'collision{n}')
for n,r in enumerate(services['player_draw_immunity']):equal(run(['reset',f"set timer {r['before']}",'draw']),[{k:r[k] for k in ('after','sprite_quadrants_drawn')}],f'draw{n}')
for n,r in enumerate(services['damage']):
 b=r['before'];a=run(['reset',f"set hp {b['hp']}",f"set pending {b['pending']}",f"set timer {b['timer']}",'damage'])[0]
 equal([{'hp':a['hp'],'pending':a['pending'],'timer':a['timer'],'ground':a['ground_flag'],'fall':a['fall_flag']}],[r['after']],f'damage{n}')
for n,r in enumerate(services['projectile_culling']):equal(run(['reset','set cx 10','set cy 1280',f"cull {r['x8']} {r['y_words']}"]),[{'culled':r['culled']}],f'cull{n}')
for n,r in enumerate(services['projectile_spawn']):
 cap=r['capacity'];a=run(['reset',f'set capacity {cap}']+['spawn 4 100 30']*(cap+1))[-1]
 equal(a['slots'],r['slots'][:4],f'allocator{n}')
 equal([{'sound_requests':sum(e['routine']=='0x9b2' for e in a['events'])}],[{'sound_requests':r['sound_requests']}],f'allocator sound{n}')

fire=load('firing-probes.json');commands=['reset','queries 1 1 1 0','set capacity 4']
for r in fire['firing_input']:commands += [f"input 0 0 0 0 0 {r['pressed']}",'move','late']
a=run(commands)[1::2]
equal([{'pressed':r['pressed'],'latch':x['latch'],'active_bullets':x['active_bullets']} for x,r in zip(a,fire['firing_input'])],fire['firing_input'],'press-edge firing')
for r in fire['projectile_motion']:
 a=run(['reset',f"bullet 0 {r['kind']} {r['before_x8']} 1280 0",'bullets 0 0'])[0]['slots'][0]
 equal([{'kind':r['kind'],'before_x8':r['before_x8'],'after_x8':a['x8'],'active':bool(a['kind'])}],[r],'projectile speed')
for r in fire['traversal']:
 c=['reset','queries 1 1 1 0','set claw 1','set cling 1','set ground 0','set fall 1', 'input 0 0 '+('1 0' if r['action']=='pull_up' else '0 1')+' 0 0']+['move','late']*3
 a=run(c)[1::2];equal([{k:x[k] for k in ('y_px','cling_state','pull_up_state')} for x in a],r['steps'],r['action'])
# Tick gate is deliberately independent from display calls; excess callbacks are discarded.
equal(run(['reset','queries 1 1 1 0','input 0 1 0 0 0 0','advance 8','advance 1','advance 90','advance 8']),[
 {'x8':16,'camera_x8':0},{'x8':16,'camera_x8':1},{'x8':16,'camera_x8':2},{'x8':16,'camera_x8':2}], 'integer gate/reset policy')
# Replay determinism: golden fixtures and general state output must not depend on process history.
script=['reset','queries 1 1 1 0','input 0 1 0 0 0 0']+['move','late','camera']*30
equal(run(script),run(script),'deterministic replay')
print(json.dumps({'golden_fixture_checks':checks,'state_rows_compared':rows_compared,'status':'PASS','scope':'All state/event fields present in player/camera/collision/services/firing stage1 records; EGA renderer blit trace excluded from phase2 core (phase1 compares actual pixels).'}))
